#!/usr/bin/env python3
"""Add the mope.io shop skins (fetched by tools/fetch-mope-io-skins.ts) to this game's shop.

Each skin gets a skin number for its animal and is registered everywhere a shop skin
must be: the web client (shop entry, in-game name, sprite swap), the account server's
shop list, the users table, and the game server (AnimalSkins and Account). Generated code
sits between "mope.io skins" marker comments and is rewritten on every run, so running it
again after fetching new skins is safe. Skin numbers are kept in tools/mope_io_imported.json.

The images are converted from WebP to the 2020 client's PNG file names using
tools/mope_io_animals.json, which says for every animal:
  per         true: the client reads every part from skins/<dir>/<number>/, so each skin
              gets a full folder (parts a skin doesn't change are copied from the default).
              false: the client only takes the skin number into account through a
              sprite swap (EXTRA_SKINS in client.js), so only the main sprite and its
              numbered frames change.
  candidates  for each 2020 file, the mope.io texture names that can stand in for it,
              best first (worked out by comparing the default animals pixel by pixel).
  transforms  scale and offset for textures drawn on a different canvas than the 2020 file.

Skins whose main sprite can't be converted, skins already in the shop under the same
name, and animals the 2020 client can't draw are skipped and listed at the end.

Usage:
    python3 tools/import_mope_io_skins.py [--skins DIR]   # DIR defaults to mope-io-skins
"""

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / "tools"
WEB_SKINS = ROOT / "web" / "skins"
CLIENT = ROOT / "web" / "client.js"
ACCOUNT_SERVER = ROOT / "backup_account" / "accountserver" / "index.js"
SQL = ROOT / "users_structure.sql"
JAVA = ROOT / "backup_server" / "server" / "src" / "main" / "java" / "io" / "mopesbox"
ANIMAL_SKINS = JAVA / "Animals" / "Info" / "AnimalSkins.java"
ACCOUNT = JAVA / "Client" / "Account.java"
MANIFEST = TOOLS / "mope_io_imported.json"

FIRST_NUMBER = 210  # skin numbers are one byte on the wire, so 210..255
CATEGORY = "mopeio"
GEM_TO_COINS = 25
UNLISTED_PRICE = 10000  # skins mope.io no longer sells

# Modern textures that hold parts the 2020 client draws separately (wings, tails,
# tentacles), or that are different art: using them would draw those parts twice.
DROP = {
    "jellyfish": {"body>jellyfish_body"},
    "komodo_dragon": {"body>komododragon"},
    "giant_scorpion": {"body>scorpion"},
}

# Animals drawn from animated parts that mope.io skins don't have: draw the skin's
# full-body sprite instead (see the phoenix's drawSkinImg in client.js).
WHOLE = {"phoenix"}

# Animals the 2020 client assembles from parts drawn around the body square (stingray
# wings and tail, swordfish nose and tail), while a mope.io skin's body is the whole
# animal. These skins are drawn as one image over the area the parts cover ("full" in
# EXTRA_SKINS). parts: (2020 file, x, y) of each part's 500px square, relative to the
# body square, as the client's drawUnderSkinImg places them. hide: sprites to blank.
FULL = {
    "stingray": {"ref": "ocean/stingray/0", "hide": ["stingray", "stingray1"],
                 "parts": [("tail", 0, -125), ("leftwing", -50, 0), ("rightwing", 50, 0), ("stingray", 0, 0)]},
    "swordfish": {"ref": "ocean/swordfish", "hide": ["swordfish", "swordfish1", "swordfish2"],
                  "parts": [("nose", 0, 75), ("tail", 0, -37.5), ("swordfish", 0, 0)]},
}

BEGIN, END = "mope.io skins: generated by tools/import_mope_io_skins.py", "end of mope.io skins"


def norm_name(s):
    return re.sub(r"[^a-z0-9]", "", s.lower().replace("the ", ""))


def clean_path(p):
    """Filesystem path for a client path like '/volcano/phoenix' or 'desert//pterodactyl'."""
    return "/".join(x for x in p.split("/") if x)


def existing_shop_names(client_js):
    i = client_js.index("mopeShopObject.prototype.getAnimalInfo")
    seg = client_js[i:i + 300000]
    names = set()
    for m in re.finditer(r"case\s*'([^']+)'\s*:\s*return\s*\[\s*[\w$]+\s*,\s*\w+\s*,\s*(?:'([^']*)'|`([^`]*)`)", seg):
        if m.group(1).startswith("mio_"):
            continue
        names.add(norm_name((m.group(2) or m.group(3)).replace("\\n", " ")))
    return names


def used_numbers(enum, rec):
    used = set()
    for m in re.finditer(r"AnimalType\." + enum + r"\s*,\s*BiomeType\.\w+\s*,\s*\d+\s*,\s*\d+\s*,\s*(\d+)", ANIMAL_SKINS.read_text()):
        used.add(int(m.group(1)))
    d = WEB_SKINS / clean_path(rec["dir"])
    if d.is_dir():
        used |= {int(x.name) for x in d.iterdir() if x.is_dir() and x.name.isdigit()}
    return used


def load_texture(path, transform):
    im = Image.open(path).convert("RGBA")
    if transform:
        s, dx, dy, w, h = transform[:5]
        canvas = Image.new("RGBA", (int(w), int(h)))
        scaled = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.LANCZOS)
        canvas.paste(scaled, (round(dx), round(dy)), scaled)
        im = canvas
    return im


def _arr(im, size=64):
    import numpy as np
    return np.asarray(im.resize((size, size), Image.BILINEAR), dtype=np.float32) / 255


def _score(a, b):
    import numpy as np
    al = np.maximum(a[..., 3], b[..., 3])[..., None]
    return float((np.abs(a[..., :3] - b[..., :3]) * al).mean() * 0.3 + np.abs(a[..., 3] - b[..., 3]).mean())


def _place(im, side, s, dx, dy):
    c = Image.new("RGBA", (side, side))
    sc = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.LANCZOS)
    c.paste(sc, (round(dx), round(dy)), sc)
    return c


def full_layout(layout):
    """The 2020 default animal assembled from its parts on a square canvas, and where
    the body square's top-left corner sits on it."""
    xs = [x for _, x, _ in layout["parts"]]; ys = [y for _, _, y in layout["parts"]]
    w, h = max(xs) - min(xs) + 500, max(ys) - min(ys) + 500
    side = int(max(w, h)) + 20
    ox, oy = (side - w) / 2 - min(xs), (side - h) / 2 - min(ys)
    canvas = Image.new("RGBA", (side, side))
    for name, x, y in layout["parts"]:
        part = Image.open(WEB_SKINS / layout["ref"] / f"{name}.png").convert("RGBA")
        canvas.alpha_composite(part, (round(ox + x), round(oy + y)))
    return canvas, ox, oy


def fit(im, target):
    """Scale and offset that lay im over target best (shape first, then colour)."""
    side = target.width; T = _arr(target); best = (9, (1, 0, 0))
    k = max(im.width, im.height)
    for s in [side * f / 100 / k for f in range(60, 101, 4)]:
        sw, sh = im.width * s, im.height * s
        for dx in [(side - sw) * f / 8 for f in range(9)]:
            for dy in [(side - sh) * f / 8 for f in range(9)]:
                v = _score(_arr(_place(im, side, s, dx, dy)), T)
                if v < best[0]:
                    best = (v, (s, dx, dy))
    s, dx, dy = best[1]
    for step in (12, 4, 1):
        for ds in (-0.01, 0, 0.01):
            for ex in (-step, 0, step):
                for ey in (-step, 0, step):
                    c = (s * (1 + ds), dx + ex, dy + ey)
                    v = _score(_arr(_place(im, side, *c)), T)
                    if v < best[0]:
                        best = (v, c)
        s, dx, dy = best[1]
    return best[1]


def make_full(animal, body_path, out):
    """Write full.png and blank the sprites it replaces; returns the drawing rect in units
    of the body radius (the body square is -1..1)."""
    layout = FULL[animal]
    target, ox, oy = full_layout(layout)
    body = Image.open(body_path).convert("RGBA")
    _place(body, target.width, *fit(body, target)).save(out / "full.png", optimize=True)
    blank = Image.new("RGBA", (500, 500))
    for name in layout["hide"]:
        blank.save(out / f"{name}.png", optimize=True)
    u = 250
    return {"x": round(-1 - ox / u, 4), "y": round(-1 - oy / u, 4), "w": round(target.width / u, 4), "h": round(target.width / u, 4)}


def same_as_default(a, b):
    if not b.exists():
        return False
    x, y = Image.open(a).convert("RGBA"), Image.open(b).convert("RGBA")
    if x.size != y.size:
        return False
    from PIL import ImageChops, ImageStat
    # compare what is visible: colours under fully transparent pixels don't count
    bg = Image.new("RGBA", x.size, (0, 0, 0, 255))
    x, y = Image.alpha_composite(bg, x), Image.alpha_composite(bg, y)
    return max(ImageStat.Stat(ImageChops.difference(x, y)).mean) < 1


def replace_block(text, anchor_re, block, tag, indent="", comment="//", after=True):
    """Put block (with markers) after the anchor line, replacing an earlier generated block."""
    start, end = f"{indent}{comment} {BEGIN} ({tag})", f"{indent}{comment} {END} ({tag})"
    text = re.sub(r"^" + re.escape(start) + r"\n.*?^" + re.escape(end) + r"\n", "", text, flags=re.S | re.M)
    m = re.search(anchor_re, text, flags=re.M)
    if not m:
        sys.exit(f"Could not find where to add the skins ({anchor_re!r}).")
    at = m.end() if after else m.start()
    if after and not text[at:at + 1] == "\n":
        at = text.index("\n", at)
    if after:
        at += 1
    return text[:at] + start + "\n" + block + end + "\n" + text[at:]


def js_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--skins", default=str(ROOT / "mope-io-skins"))
    args = ap.parse_args()
    src = Path(args.skins)
    report = json.loads((src / "skins.json").read_text())
    animals = json.loads((TOOLS / "mope_io_animals.json").read_text())
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    client_js = CLIENT.read_text()
    have_names = existing_shop_names(client_js)

    # Remove the images of an earlier run; they are written again below.
    for item in manifest.values():
        d = WEB_SKINS / item["folder"]
        if d.is_dir():
            shutil.rmtree(d)

    imported, skipped = [], []
    taken = {}
    for item in manifest.values():
        taken.setdefault(item["type"], set()).add(item["number"])
    for s in sorted(report["skins"], key=lambda s: s["id"]):
        sid, a = s["id"], s["animal"]
        rec = animals.get(a)
        if rec is None:
            skipped.append((sid, "animal not in the 2020 game"))
            continue
        if norm_name(s["name"]) in have_names:
            skipped.append((sid, "already in the shop"))
            continue
        files = {f.split("/", 3)[3][:-5]: src / f for f in s["files"]
                 if f.count("/") == 3 and f.endswith(".webp") and not f.endswith(".ui.webp")}
        drop = DROP.get(a, set())

        def pick(target):
            for n in rec["candidates"].get(target, []):
                if n in files and f"{n}>{target}" not in drop:
                    return n, rec["transforms"].get(f"{n}>{target}")
            return None, None

        main_target = rec["main"] if rec["per"] else rec["files"][0]
        plan = {t: pick(t) for t in rec["files"]}
        body_target = next((t for t, (n, _) in plan.items() if n == "body"), None)
        if a in FULL:
            if "body" not in files:
                skipped.append((sid, "main sprite can't be converted"))
                continue
        elif plan.get(main_target, (None,))[0] is None and body_target is None:
            skipped.append((sid, "main sprite can't be converted"))
            continue

        item_name = "mio_" + sid
        if len(item_name) > 64:
            skipped.append((sid, "id too long for a database column"))
            continue
        prev = manifest.get(item_name)
        if prev and prev["type"] == rec["id"]:
            number = prev["number"]
        else:
            used = used_numbers(rec["enum"], rec) | taken.get(rec["id"], set())
            free = [n for n in range(FIRST_NUMBER, 256) if n not in used]
            if not free:
                skipped.append((sid, "no free skin number"))
                continue
            number = free[0]
        taken.setdefault(rec["id"], set()).add(number)

        folder = f"{clean_path(rec['dir'])}/{number}"
        out = WEB_SKINS / folder
        out.mkdir(parents=True, exist_ok=True)
        written = []
        if a in FULL:
            rect = make_full(a, files["body"], out)
            base_dir = f"{rec['dir'].rstrip('/')}/{number}"
            entry = {
                "itemName": item_name, "id": sid, "animal": a, "type": rec["id"], "number": number,
                "folder": folder, "name": s["name"], "image": f"{base_dir}/full",
                "price": price_of(s), "per": rec["per"], "written": ["full"],
                "full": dict(img=f"{clean_path(rec['dir'])}/{number}/full", **rect),
            }
            if rec.get("base"):
                # the sprite swap points every pose at the blank sprites
                entry["swap"] = {"base": rec["base"].replace("{N}", str(number)), "sprite": f"{base_dir}/{rec['main']}",
                                 "variants": [n[len(rec["main"]):] for n in FULL[a]["hide"]]}
            imported.append(entry)
            continue
        for target in rec["files"]:
            n, tf = plan[target]
            dest = out / f"{target}.png"
            if n:
                load_texture(files[n], tf).save(dest, optimize=True)
                written.append(target)
            elif rec["per"]:
                ref = WEB_SKINS / clean_path(rec["ref"]) / f"{target}.png"
                if ref.exists():
                    shutil.copyfile(ref, dest)
        if written and all(same_as_default(out / f"{w}.png", WEB_SKINS / clean_path(rec["ref"]) / f"{w}.png") for w in written):
            shutil.rmtree(out)
            taken[rec["id"]].discard(number)
            skipped.append((sid, "looks exactly like the default animal"))
            continue
        if rec["per"]:
            # parts kept in subfolders (phoenix flames) stay the default ones
            ref_dir = WEB_SKINS / clean_path(rec["ref"])
            for sub in ref_dir.iterdir():
                if sub.is_dir() and not sub.name.isdigit():
                    shutil.copytree(sub, out / sub.name, dirs_exist_ok=True)
        sprite_path = f"{rec['dir'].rstrip('/')}/{number}/{main_target}"
        shop_image = sprite_path if main_target in written else f"{rec['dir'].rstrip('/')}/{number}/{body_target}"
        entry = {
            "itemName": item_name, "id": sid, "animal": a, "type": rec["id"], "number": number,
            "folder": folder, "name": s["name"], "image": shop_image,
            "price": price_of(s), "per": rec["per"], "written": written,
        }
        base = rec.get("base")
        if base:
            # Animals that ignore the skin number (or whose path has no file name) need a swap.
            base = base.replace("{N}", str(number))
            entry["swap"] = {"base": base, "sprite": sprite_path,
                             "variants": [v for v in rec["variants"] if (main_target if v == "" else rec["main"] + v) in written] or [""]}
        imported.append(entry)

    manifest = {e["itemName"]: {k: e[k] for k in ("type", "number", "folder")} for e in imported}
    MANIFEST.write_text(json.dumps(manifest, indent=1, sort_keys=True) + "\n")
    write_code(imported, animals)

    print(f"Imported {len(imported)} skins into the shop's mope.io tab.")
    reasons = {}
    for sid, why in skipped:
        reasons.setdefault(why, []).append(sid)
    for why, ids in reasons.items():
        print(f"Skipped {len(ids)} ({why}): {', '.join(ids)}")


def price_of(s):
    if s.get("currency") == "GEMS":
        return s["price"] * GEM_TO_COINS
    return s.get("price") or UNLISTED_PRICE


def write_code(items, animals):
    enum_of = {r["id"]: r["enum"] for r in animals.values()}
    java_of = {r["id"]: r["java"] for r in animals.values()}

    # web client: shop entries, in-game names and sprite swaps
    js = CLIENT.read_text()
    cases = "".join(
        f"        case {js_str(e['itemName'])}:\n"
        f"            return [{e['type']}, {e['number']}, {js_str(e['name'].replace(' ', chr(10), 1))}, {js_str(clean_path(e['image']))}];\n"
        for e in items)
    js = replace_block(js, r"^\s*// Shop skins imported from mope\.trygames\.party: \[animal type, skin number, name, image\]$",
                       cases, indent="        ", tag="shop entries")
    extra = {}
    for e in items:
        x = {"name": e["name"]}
        if "swap" in e:
            x.update(e["swap"], keep=True)
        if "full" in e:
            x["full"] = e["full"]
        if e["animal"] in WHOLE:
            x["whole"] = True
        extra[f"{e['type']}_{e['number']}"] = x
    js = replace_block(js, r"^function addExtraSkinSupport\(obj\) \{$",
                       "Object.assign(EXTRA_SKINS, " + json.dumps(extra, indent=4) + ");\n", after=False, tag="names and sprites")
    CLIENT.write_text(js)

    # account server: shop list
    acc = ACCOUNT_SERVER.read_text()
    entries = "".join(
        f"    {{ coinsPrice: {e['price']}, shopCategory: '{CATEGORY}', itemName: \"{e['itemName']}\" }},\n" for e in items)
    acc = replace_block(acc, r"^    // Imported from mope\.trygames\.party$", entries, indent="    ", after=False, tag="shop list")
    ACCOUNT_SERVER.write_text(acc)

    # users table
    sql = SQL.read_text()
    cols = "".join(f"  `{e['itemName']}` int(11) DEFAULT NULL,\n" for e in items)
    sql = replace_block(sql, r"^  `skin_blackdragon` int\(11\) DEFAULT NULL,$", cols, indent="  ", comment="--", after=False, tag="columns")
    SQL.write_text(sql)

    # game server
    skins = ANIMAL_SKINS.read_text()
    lines = []
    for e in items:
        j = java_of[e["type"]]
        rare = f", {j['rare']}" if j.get("rare") else ""
        lines.append(f"    public static AnimalInfo {e['itemName']}_skin = new AnimalInfo(AnimalType.{enum_of[e['type']]}, "
                     f"{j['biome']}, {j['tier']}, {j['ability']}, {e['number']}{rare}); // {e['name']}\n")
    skins = replace_block(skins, r"^    // very dangerous shenanigans$", "".join(lines), indent="    ", after=False, tag="skins")
    ANIMAL_SKINS.write_text(skins)

    account = ACCOUNT.read_text()
    fields = "".join(f"    public int {e['itemName']};\n" for e in items)
    account = replace_block(account, r"^    // Shop skins imported from mope\.trygames\.party$", fields, indent="    ", after=False, tag="owned flags")
    ACCOUNT.write_text(account)


if __name__ == "__main__":
    main()
