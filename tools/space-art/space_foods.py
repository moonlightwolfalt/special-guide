#!/usr/bin/env python3
"""The space foods: one list that the game server, the web client and the pictures
are all made from, so the three always agree.

Each food's number is its place in FOODS, and the server sends that number to the
client, so add new foods at the end.

XP for eating one is  base + share x (the eater's current XP). The best pumpkin
goal gives a fifth of your XP, so every share here is above 0.2: even the smallest
space food is worth more than any pumpkin, and the biggest double your XP.

Usage: python3 tools/space-art/space_foods.py   (from the repository root)
  writes backup_server/.../Objects/Eatable/SpaceFoodKind.java,
  the SPACE_FOODS list in web/client.js, and web/img/space/food/*.png
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from space_food_art import ELEMENTS, WAVELENGTHS, all_food_art  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]

# picture, radius, xp share, xp base, how many float in space at once
FOODS = [
    ('space/planet_rocky', 80, 0.35, 8000, 4),
    ('space/planet_ocean', 85, 0.35, 8000, 4),
    ('space/planet_ringed', 100, 0.36, 8500, 4),
    ('space/star', 110, 0.40, 10000, 3),
    ('space/star_system', 150, 0.45, 12000, 2),
    ('space/black_hole', 130, 0.50, 15000, 2),
    ('space/quasar', 130, 0.55, 17000, 2),
    ('space/galaxy', 180, 0.60, 20000, 2),
    ('space/galaxy_cluster', 210, 0.70, 25000, 1),
    ('space/supercluster', 240, 0.80, 30000, 1),
    ('space/cluster_filaments', 260, 0.90, 35000, 1),
    ('space/observable_universe', 300, 1.00, 50000, 1),
    ('space/food/asteroid_rock', 45, 0.25, 4000, 12),
    ('space/food/asteroid_iron', 45, 0.25, 4000, 12),
    ('space/food/satellite', 40, 0.28, 5000, 6),
    ('space/food/satellite_dish', 40, 0.28, 5000, 6),
    ('space/food/moon_grey', 55, 0.30, 6000, 6),
    ('space/food/moon_ice', 55, 0.30, 6000, 6),
]
FOODS += [(f'space/food/light_{name}', 26, 0.21, 2000, 3) for name, *_ in WAVELENGTHS]
FOODS += [(f'space/food/element_{i:03d}_{sym}', 28, 0.22, 2500, 1) for i, (sym, *_) in enumerate(ELEMENTS, 1)]
assert len(FOODS) < 256, 'the kind is sent as one byte'


def write_java():
    rows = ',\n'.join(f'        new SpaceFoodKind("{pic.split("/")[-1]}", {r}, {share}, {base}, {count})'
                      for pic, r, share, base, count in FOODS)
    java = f'''package io.mopesbox.Objects.Eatable;

// Generated by tools/space-art/space_foods.py; edit that file, not this one.
// Index in KINDS is the kind number the client draws (SPACE_FOODS in web/client.js).
public final class SpaceFoodKind {{
    public final String name;
    public final double radius;
    // eating one gives xpBase + xpShare x the eater's current XP
    public final double xpShare;
    public final int xpBase;
    // how many of this kind float in space at once
    public final int count;

    private SpaceFoodKind(String name, double radius, double xpShare, int xpBase, int count) {{
        this.name = name;
        this.radius = radius;
        this.xpShare = xpShare;
        this.xpBase = xpBase;
        this.count = count;
    }}

    public static final SpaceFoodKind[] KINDS = {{
{rows}
    }};
}}
'''
    path = ROOT / 'backup_server/server/src/main/java/io/mopesbox/Objects/Eatable/SpaceFoodKind.java'
    path.write_text(java)
    return path


def write_js():
    items = ',\n'.join(f"    'img/{pic}.png'" for pic, *_ in FOODS)
    block = (f'// <space-foods> generated by tools/space-art/space_foods.py\n'
             f'// Picture for each space food kind, by the kind number the server sends.\n'
             f'var SPACE_FOODS = [\n{items}\n];\n// </space-foods>')
    path = ROOT / 'web/client.js'
    src = path.read_text()
    pattern = re.compile(r'// <space-foods>.*?// </space-foods>', re.S)
    if not pattern.search(src):
        raise SystemExit('web/client.js has no // <space-foods> ... // </space-foods> block')
    path.write_text(pattern.sub(lambda m: block, src, count=1))
    return path


def render_pictures():
    out = ROOT / 'web/img/space/food'
    with tempfile.TemporaryDirectory() as tmp:
        for name, art in all_food_art().items():
            Path(tmp, f'{name}.svg').write_text(art)
        subprocess.run(['node', str(ROOT / 'tools/space-art/render.js'), tmp, str(out), '256'], check=True)
    return out


if __name__ == '__main__':
    print('wrote', write_java())
    print('wrote', write_js())
    print('rendered', render_pictures())
    print(f'{len(FOODS)} space foods')
